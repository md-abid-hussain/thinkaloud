// Builds db/seed_challenges.sql from learning-java/INDEX.md (titles, paths and roadmap levels only).
// Usage: node scripts/import-index.mjs <path to INDEX.md>

import { readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/import-index.mjs <path to INDEX.md>');
  process.exit(1);
}

const base = {
  roadmap_sh: 'https://roadmap.sh/projects/',
  coding_challenges: 'https://codingchallenges.fyi/challenges/',
};
const levels = { Beginner: 'beginner', Intermediate: 'intermediate', Advanced: 'advanced' };
const quote = (s) => `'${s.replace(/'/g, "''")}'`;

let source = null;
const rows = [];
for (const line of readFileSync(input, 'utf8').split(/\r?\n/)) {
  if (line.startsWith('## roadmap.sh')) source = 'roadmap_sh';
  else if (line.startsWith('## Coding Challenges')) source = 'coding_challenges';
  else if (source && /^\|\s*\d+\s*\|/.test(line)) {
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (source === 'roadmap_sh') {
      const [, level, title, path] = cells;
      rows.push({ source, slug: path, title, level: levels[level] ?? null });
    } else {
      const [, title, path] = cells;
      rows.push({ source, slug: path, title, level: null });
    }
  }
}

const counts = rows.reduce((n, r) => ({ ...n, [r.source]: (n[r.source] ?? 0) + 1 }), {});
const values = rows.map(
  (r) =>
    `  (${quote(r.source)}, ${quote(r.slug)}, ${quote(r.title)}, ${quote(base[r.source] + r.slug)}, ${
      r.level ? quote(r.level) : 'null'
    })`
);

const sql = `-- Generated by scripts/import-index.mjs from learning-java/INDEX.md. Do not edit by hand.
-- ${rows.length} projects: ${counts.coding_challenges} Coding Challenges and ${counts.roadmap_sh} roadmap.sh.
-- Rows that already exist (for example the reviewed wc sample) are left as they are.

begin;

insert into challenge (source, slug, title, source_url, level) values
${values.join(',\n')}
on conflict (source, slug) do nothing;

commit;
`;

writeFileSync(new URL('../seed_challenges.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} projects`, counts);
