// Writes content/REVIEW_SHEET.md: every predict and trace key with its derivation, the proof that
// was run and what it returned, plus the concepts nobody has reviewed yet.
//
//   node scripts/review-sheet.mjs
//
// It runs the same check as import-content.mjs, so the sheet is only written when everything passes.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { check, CONTENT_DIR } from './import-content.mjs';

const r = await check();
if (!r.ok) {
  for (const m of r.errors) console.error(`ERROR    ${m}`);
  console.error('\nThe check failed, so the review sheet was not written.');
  process.exit(1);
}

const show = (v) => (Array.isArray(v) ? v.join(', ') : String(v));
const indent = (text) => text.split('\n').map((l) => `    ${l}`).join('\n');
const oneLine = (text) => String(text).replace(/\s+/g, ' ').trim();
const MATCH = {
  number_exact: 'exactly this one number',
  numbers_all: 'all of these numbers',
  text_ci: 'this text, any case',
};

const out = [
  '# Review sheet',
  '',
  'Generated by `node scripts/review-sheet.mjs` from `db/`. Do not edit by hand; fix the YAML or the proof and run it again.',
  '',
  'For each key: read the prompt, work the answer out yourself, then compare with the expected answer, the derivation and',
  'what the proof script returned. Every proof below was run and matched its key, otherwise this sheet would not exist.',
  'Proofs live in `content/proofs/<project>.mjs` and can be run again on their own.',
  '',
  `Status: ${r.summary.generatedProjects} generated projects, ${r.summary.reviewedProjects} reviewed, ${r.keys.length} keys, ${r.summary.teachBacks} teach-backs.`,
  '',
  '## Contents',
  '',
];

const projects = r.content.projects.map(({ data }) => data);
for (const p of projects) {
  const n = r.keys.filter((k) => k.project === p.project.slug).length;
  out.push(`- [${p.project.title}](#${p.project.slug}) (${p.project.slug}): ${n} keys, status ${p.project.status}`);
}
out.push(
  `- [Prompts to check: the tool on a made-up input](#prompts-to-check-the-tool-on-a-made-up-input) (${r.flags.length})`,
  '- [Concepts not yet reviewed](#concepts-not-yet-reviewed)',
  ''
);

for (const p of projects) {
  const slug = p.project.slug;
  out.push(`<a id="${slug}"></a>`, '', `## ${p.project.title}`, '', `Source: ${p.project.source_url}. Proofs: \`content/proofs/${slug}.mjs\`.`, '');
  for (const k of r.keys.filter((x) => x.project === slug)) {
    const m = p.milestones[Number(k.id.split('.')[0]) - 1];
    const s = m.steps[Number(k.id.split('.')[1]) - 1];
    out.push(
      `### ${k.id} ${s.title} (${k.kind})`,
      '',
      `- [ ] checked`,
      '',
      `**Prompt.** ${oneLine(k.prompt)}`,
      ''
    );
    if (k.snippet) out.push('Snippet:', '', indent(k.snippet), '');
    out.push(
      `**Expected** (${MATCH[k.match]}): **${show(k.expected)}**`,
      '',
      `**Derivation.** ${oneLine(k.derivation)}`,
      '',
      `**Proof returned:** ${JSON.stringify(k.proof.output)} ${k.proof.ok ? '(matches)' : '(DOES NOT MATCH)'}`,
      '',
      '<details><summary>Proof source</summary>',
      '',
      '```js',
      k.proof.source,
      '```',
      '',
      '</details>',
      ''
    );
  }
}

out.push(
  '## Prompts to check: the tool on a made-up input',
  '',
  'Content v2 bans Think tasks whose only lesson is "you ran the tool in your head". The checker cannot tell for',
  'certain, so it flags prompts that look like one. Keep a flagged prompt only if the answer is a fact about the',
  'concept, not about a toy input.',
  '',
  '| Project | Step | Kind | Sign | Prompt |',
  '|---|---|---|---|---|'
);
for (const f of r.flags) {
  out.push(`| ${f.project} | ${f.id} | ${f.kind} | ${f.sign} | ${oneLine(f.prompt).replace(/\|/g, '/')} |`);
}
if (!r.flags.length) out.push('| | | | none flagged | |');
out.push('');

out.push('## Concepts not yet reviewed', '', '| Concept | Area | Brief |', '|---|---|---|');
for (const c of r.content.catalogue.concepts.filter((c) => c.status !== 'reviewed')) {
  out.push(`| ${c.slug} | ${c.area} | ${oneLine(c.brief).replace(/\|/g, '/')} |`);
}
out.push('');

writeFileSync(join(CONTENT_DIR, 'REVIEW_SHEET.md'), out.join('\n'));
console.log(`Wrote content/REVIEW_SHEET.md with ${r.keys.length} keys from ${projects.length} projects.`);
await r.db.close();
